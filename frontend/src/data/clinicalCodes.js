export const getCodeName = (code) => {
  if (!code) return '';
  const trimmed = code.trim().toUpperCase();

  const estudio = ESTUDIOS_BAJO_ANESTESIA.find(e => e.code.toUpperCase() === trimmed || e.name.toUpperCase() === trimmed);
  if (estudio) return estudio.name;

  const match = CLINICAL_NOMENCLADOR.find(c => c.code === trimmed);
  if (match) return match.name;

  const smModule = MODULOS_SM.find(m => m.code === trimmed);
  if (smModule) return smModule.name;

  const iosfa = CODIGOS_IOSFA.find(c => c.code === trimmed);
  if (iosfa) return iosfa.name;

  const tryWithZero = CLINICAL_NOMENCLADOR.find(c => c.code === '0' + trimmed);
  if (tryWithZero) return tryWithZero.name;

  const tryWithoutZero = CLINICAL_NOMENCLADOR.find(c => c.code.replace(/^0+/, '') === trimmed.replace(/^0+/, ''));
  if (tryWithoutZero) return tryWithoutZero.name;

  return '';
};

export const resolveCodeLine = (code) => {
  const trimmed = code?.trim();
  if (!trimmed) return null;
  const name = getCodeName(trimmed);
  return name ? `${trimmed} - ${name}` : trimmed;
};

export const expandCodes = (codesInput, isSwissMedical = false, isIOSFA = false) => {
  if (!codesInput) return [];
  let raw = [];
  if (Array.isArray(codesInput)) {
    raw = codesInput.map(c => typeof c === 'object' && c ? (c.codigo || c.name || '') : String(c)).filter(Boolean);
  } else if (typeof codesInput === 'string') {
    if (codesInput.includes('\n')) {
      raw = codesInput.split('\n').map(c => c.trim()).filter(Boolean);
    } else {
      const trimmed = codesInput.trim();
      const matchEstudio = ESTUDIOS_BAJO_ANESTESIA.find(e => e.code.toLowerCase() === trimmed.toLowerCase() || e.name.toLowerCase() === trimmed.toLowerCase());
      if (matchEstudio) {
        raw = [trimmed];
      } else {
        let temp = trimmed;
        const foundEstudios = [];
        for (const est of ESTUDIOS_BAJO_ANESTESIA) {
          if (temp.toLowerCase().includes(est.name.toLowerCase())) {
            foundEstudios.push(est.name);
          }
        }
        if (foundEstudios.length > 0) {
          raw = foundEstudios;
        } else {
          raw = codesInput.split(/\s+/).filter(c => c.trim() !== '');
        }
      }
    }
  } else {
    return [];
  }
  const result = [];
  for (const code of raw) {
    const trimmed = code.trim();
  const estudio = ESTUDIOS_BAJO_ANESTESIA.find(e => e.code.toLowerCase() === trimmed.toLowerCase() || e.name.toLowerCase() === trimmed.toLowerCase());
    if (estudio) {
      result.push(estudio.name);
      continue;
    }
    const isModuleCode = MODULOS_SM.some(m => m.code === trimmed);
    if (isModuleCode) {
      const smModule = MODULOS_SM.find(m => m.code === trimmed);
      result.push(`${trimmed} ${smModule.name}`);
    } else {
      const parentModule = isSwissMedical
        ? MODULOS_SM.find(m => m.includes && m.includes.includes(trimmed))
        : null;
      const iosfaMatch = isIOSFA ? CODIGOS_IOSFA.find(c => c.generalCode === trimmed || c.code === trimmed) : null;
      if (parentModule) {
        const name = getCodeName(trimmed);
        result.push(name ? `${parentModule.code} ${parentModule.name} - ${trimmed} ${name}` : `${parentModule.code} ${parentModule.name} - ${trimmed}`);
      } else if (iosfaMatch) {
        const name = getCodeName(trimmed);
        result.push(`${iosfaMatch.code} (${trimmed}) ${name || iosfaMatch.name}`);
      } else {
        const name = getCodeName(trimmed);
        result.push(name ? `${trimmed} ${name}` : trimmed);
      }
    }
  }
  return result;
};

export const searchCodes = (query, isSwissMedical = false, tipoProcedimiento = 'CIRUGIA') => {
  if (!query || query.trim().length < 2) return [];
  const q = query.toLowerCase().trim();
  const results = [];

  if (tipoProcedimiento === 'ESTUDIO') {
    ESTUDIOS_BAJO_ANESTESIA.forEach(e => {
      if (e.code.toLowerCase().includes(q) || e.name.toLowerCase().includes(q)) {
        results.push({ code: e.code, name: e.name, type: 'estudio' });
      }
    });
    return results.slice(0, 8);
  }

  if (isSwissMedical) {
    MODULOS_SM.forEach(m => {
      if (m.code.includes(q) || m.name.toLowerCase().includes(q)) {
        results.push({ code: m.code, name: m.name, type: 'modulo', parentModule: null });
      }
    });
  }

  CLINICAL_NOMENCLADOR.forEach(c => {
    if (c.code.includes(q) || c.name.toLowerCase().includes(q)) {
      const parentModule = isSwissMedical
        ? MODULOS_SM.find(m => m.includes && m.includes.includes(c.code))
        : null;
      results.push({ code: c.code, name: c.name, type: 'nomenclador', parentModule });
    }
  });

  CODIGOS_IOSFA.forEach(c => {
    if (c.code.includes(q) || c.generalCode.includes(q) || c.name.toLowerCase().includes(q)) {
      const parentModule = isSwissMedical
        ? MODULOS_SM.find(m => m.includes && m.includes.includes(c.code))
        : null;
      results.push({ code: c.code, name: c.name, type: 'iosfa', parentModule, generalCode: c.generalCode });
    }
  });

  return results.slice(0, 8);
};
